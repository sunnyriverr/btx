"""Run only four maintained portable tests; no external commands within tests."""
from pathlib import Path
import datetime, hashlib, importlib.util, json, os, shutil, subprocess, sys, time, unittest
from unittest import mock

root = Path(sys.argv[1]).resolve()
label = sys.argv[2]
out = Path(sys.argv[3]).resolve()
names = [
    "test_third_party_roots_include_packages_nested_below_stdlib",
    "test_third_party_roots_are_top_level_packages_and_modules",
    "test_stdlib_copy_leaves_out_tests_gui_bytecode_and_outside_links",
    "test_refuses_a_third_party_module_outside_the_prefix",
]
attempts = []
def deny(*args, **kwargs):
    attempts.append(repr(args[:1]))
    raise AssertionError("External command prohibited in focused portable checks")
start = time.monotonic()
test_file = root / "test/util/package_release_archive_test.py"
module_file = root / "scripts/release/bundle_python_runtime.py"
spec = importlib.util.spec_from_file_location("focused_package_archive_tests", test_file)
module = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = module
log = out / (label + ".log")
with mock.patch.object(subprocess, "Popen", side_effect=deny):
    spec.loader.exec_module(module)
    suite = unittest.TestSuite(module.BundlePythonRuntimeTest(name) for name in names)
    with log.open("w") as stream:
        result = unittest.TextTestRunner(stream=stream, verbosity=2).run(suite)
row = {
    "utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
    "label": label, "python": sys.version, "platform": sys.platform,
    "names": names, "methods_run": result.testsRun,
    "failures": [{"test": str(test), "trace": trace} for test, trace in result.failures],
    "errors": [{"test": str(test), "trace": trace} for test, trace in result.errors],
    "skipped": [(str(test), reason) for test, reason in result.skipped],
    "external_command_attempts": attempts, "seconds": time.monotonic() - start,
    "test_file_sha256": hashlib.sha256(test_file.read_bytes()).hexdigest(),
    "bundler_sha256": hashlib.sha256(module_file.read_bytes()).hexdigest(),
    "minimum_expected_scope": "Portable selector/copy/prefix controls only; no native or package integration",
}
(out / (label + ".json")).write_text(json.dumps(row, indent=2) + "\n")
print(json.dumps({"label": label, "methods": row["methods_run"], "failures": len(row["failures"]),
                  "errors": len(row["errors"]), "skips": len(row["skipped"]),
                  "external_attempts": len(attempts), "seconds": row["seconds"]}))
sys.exit(0 if result.wasSuccessful() else 1)
